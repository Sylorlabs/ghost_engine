pub fn main() !void {
    var arena = std.heap.ArenaAllocator.init(std.heap.page_allocator);
    defer arena.deinit();
    const aa = arena.allocator();

    var args = try std.process.argsWithAllocator(aa);
    defer args.deinit();
    _ = args.next();

    var source_path: []const u8 = "src/adapters/phase_lattice_inventor.zig";
    var doc_path: []const u8 = "docs/research/phase_lattice_inventor.md";
    while (args.next()) |arg| {
        if (std.mem.startsWith(u8, arg, "--source=")) source_path = arg["--source=".len..] else if (std.mem.startsWith(u8, arg, "--doc=")) doc_path = arg["--doc=".len..];
    }

    const h = prototypeHash();
    const phase_count = 5 + @as(usize, @intCast(h % 4));
    var phase_stride = 17 + @as(usize, @intCast((h >> 8) % 73));
    if (phase_stride % 2 == 0) phase_stride += 1;
    const braid_period = 64 + @as(usize, @intCast((h >> 16) % 193));

    try writeEngineSource(source_path, phase_count, phase_stride, braid_period);
    try writeDesignDoc(doc_path, phase_count, phase_stride, braid_period);

    const stdout = std.io.getStdOut().writer();
    try stdout.print("=== GEOMETRY ARTIFACT COMPILER ===\n", .{});
    try stdout.print("source={s}\ndoc={s}\n", .{ source_path, doc_path });
    try stdout.print("phase_count={d} phase_stride={d} braid_period={d} prototype_hash=0x{X}\n", .{
        phase_count,
        phase_stride,
        braid_period,
        h,
    });
}
