const std = @import("std");

// --- GEOMETRY ARTIFACT COMPILER ---
//
// Converts the generated outside-envelope geometry engine into a second-stage
// invention artifact: a readable design note plus a standalone Zig engine.
// This is still local and deterministic. It does not ask a model for a design.

const AlienPrototype = [_]u64{
    0x4B7A37C9F92B99F2,
    0x3961A37302DE0890,
    0xC4EB492A01BCF34F,
    0x264DC82DA48D8DE1,
    0xB1075EF0F9B2A400,
    0xBA101CDFDC4C4035,
    0xF7B928AF4066565A,
    0x2B10884F61377845,
};

const GenomeNameHash: u64 = 0x9BBCD5731B3CB1EA;
const GenomeSeed: u64 = 0xD3DB779DA6DD8E30;
const RepairPasses: usize = 45;
const LockPeriod: usize = 2;
const CurlStride: usize = 29;
const CurlSpan: usize = 21;
const NoveltyPressure: i128 = 1024;
const CurlAmplitude: i128 = 64;

fn splitMix64(x: u64) u64 {
    var z = x +% 0x9E3779B97F4A7C15;
    z = (z ^ (z >> 30)) *% 0xBF58476D1CE4E5B9;
    z = (z ^ (z >> 27)) *% 0x94D049BB133111EB;
    return z ^ (z >> 31);
}

fn prototypeHash() u64 {
    var h: u64 = GenomeNameHash ^ GenomeSeed;
    for (AlienPrototype, 0..) |word, idx| {
        h = splitMix64(h ^ word ^ @as(u64, @intCast(idx * 0x101)));
    }
    return h;
}

fn writeDesignDoc(path: []const u8, phase_count: usize, phase_stride: usize, braid_period: usize) !void {
    if (std.fs.path.dirname(path)) |dir| if (dir.len != 0) try std.fs.cwd().makePath(dir);
    var file = try std.fs.cwd().createFile(path, .{ .truncate = true });
    defer file.close();
    const w = file.writer();

    try w.print(
        \\# Phase Lattice Inventor
        \\
        \\Generated by `geometry_artifact_compiler.zig` from the outside-envelope geometry
        \\discovered by `generated_geometry_invention.zig`.
        \\
