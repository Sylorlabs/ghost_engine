        \\1. Keep the outside-VSA prototype as the root language.
        \\2. Spawn several phase views of that geometry.
        \\3. Repair each phase against Flame laws without allowing collapse back into the
        \\   VSA concept envelope.
        \\4. Select the lowest-closure surviving phase.
        \\5. Treat the selected phase as the next invention substrate.
        \\
        \\This is not a proof of superhuman invention. It is a concrete local engine that
        \\thinks in geometry first and English only through this compiled artifact.
        \\
        \\## Generated Parameters
        \\
        \\- genome hash: `0x{X}`
        \\- phase count: `{d}`
        \\- phase stride: `{d}`
        \\- braid period: `{d}`
        \\- repair passes: `{d}`
        \\- lock period: `{d}`
        \\- curl stride: `{d}`
        \\- curl span: `{d}`
        \\- novelty pressure: `{d}`
        \\- curl amplitude: `{d}`
        \\
        \\## Run
        \\
        \\```sh
        \\./zig-out/bin/phase_lattice_inventor --trials=16 --csv=results/phase_lattice_inventor.csv
        \\```
        \\
        \\## What Would Count As Extraordinary
        \\
        \\The next bar is not better poetry. The next bar is a generated artifact that:
        \\
        \\- stays outside the VSA envelope,
        \\- beats the prior generated engine's `14829513` closure score,
        \\- emits a readable new algorithm or engine design,
        \\- then survives a holdout benchmark that was not used to generate it.
